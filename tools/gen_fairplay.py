"""Generate the pure-Python FairPlay (playfair) data + garble() port.

Reads the reference C sources of the open-source "playfair" FairPlay SAP
implementation (as shipped in UxPlay / RPiPlay / shairplay, lib/playfair and
lib/fairplay_playfair.c) and writes:

  icast/fairplay/_tables.py   lookup tables as base64 blobs
  icast/fairplay/_garble.py   garble() translated to Python that runs on
                                      C-integer-semantics objects (see _cint.py)

Nothing from the C sources is compiled or executed: arrays are parsed as data and
the straight-line garble() body is translated statement by statement.

Usage:  python tools/gen_fairplay.py <path-to-UxPlay/lib>
"""
import base64
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "icast" / "fairplay"

NUM = re.compile(r"0[xX][0-9a-fA-F]+|\d+")


def parse_arrays(src: str) -> dict:
    """Return {name: [ints]} for every initialised C array in src (flattened)."""
    out = {}
    pat = re.compile(
        r"(?:unsigned\s+char|unsigned\s+long|uint32_t|uint8_t|char|int)\s+(\w+)\s*((?:\[[^\]]*\])+)\s*=\s*\{(.*?)\}\s*;",
        re.S,
    )
    for m in pat.finditer(src):
        name, body = m.group(1), m.group(3)
        body = re.sub(r"//[^\n]*", "", body)
        out[name] = [int(n, 0) for n in NUM.findall(body)]
    return out


def strip_comments(src: str) -> str:
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    return re.sub(r"//[^\n]*", "", src)


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode()


def gen_tables(lib: Path):
    pf = lib / "playfair"
    arrays = {}
    arrays.update(parse_arrays((pf / "omg_hax.h").read_text()))
    arrays.update(parse_arrays(strip_comments((pf / "omg_hax.c").read_text())))
    sap = parse_arrays(strip_comments((pf / "sap_hash.c").read_text()))
    fp = parse_arrays(strip_comments((lib / "fairplay_playfair.c").read_text()))

    byte_tables = {
        "MESSAGE_KEY": (arrays["message_key"], 4 * 144),
        "MESSAGE_IV": (arrays["message_iv"], 4 * 16),
        "Z_KEY": (arrays["z_key"], 16),
        "X_KEY": (arrays["x_key"], 16),
        "T_KEY": (arrays["t_key"], 16),
        "TABLE_S1": (arrays["table_s1"], 0x28 * 256),
        "TABLE_S2": (arrays["table_s2"], 144 * 256),
        "TABLE_S3": (arrays["table_s3"], 16 * 256),
        "TABLE_S4": (arrays["table_s4"], 144 * 256),
        "TABLE_S10": (arrays["table_s10"], 16 * 256),
        "INDEX_MANGLE": (arrays["index_mangle"], 11),
        "INITIAL_SESSION_KEY": (arrays["initial_session_key"], 16),
        "STATIC_SOURCE_1": (arrays["static_source_1"], 17),
        "STATIC_SOURCE_2": (arrays["static_source_2"], 47),
        "DEFAULT_SAP": (arrays["default_sap"], None),
        "SAP_BUFFER0": (sap["buffer0"], 20),
        "SAP_BUFFER2": (sap["buffer2"], 35),
        "SAP_BUFFER4": (sap["buffer4"], 21),
        "REPLY_MESSAGE": (fp["reply_message"], 4 * 142),
        "FP_HEADER": (fp["fp_header"], 12),
    }
    word_tables = {
        "TABLE_S5": (arrays["table_s5"], 256),
        "TABLE_S6": (arrays["table_s6"], 256),
        "TABLE_S7": (arrays["table_s7"], 256),
        "TABLE_S8": (arrays["table_s8"], 256),
        "TABLE_S9": (arrays["table_s9"], 0x400),
    }

    lines = [
        '"""FairPlay SAP lookup tables (generated by tools/gen_fairplay.py; do not edit).',
        "",
        "Data originates from the open-source playfair implementation (GPL-3.0),",
        'see licenses/playfair-LICENSE.md."""',
        "import base64 as _b",
        "import struct as _s",
        "",
        "def _w(s):",
        "    d = _b.b64decode(s)",
        "    return _s.unpack('<%dI' % (len(d) // 4), d)",
        "",
    ]
    for name, (vals, expect) in byte_tables.items():
        if expect is not None and len(vals) != expect:
            raise SystemExit(f"{name}: expected {expect} values, got {len(vals)}")
        data = bytes(v & 0xFF for v in vals)
        lines.append(f"{name} = _b.b64decode('{b64(data)}')")
    for name, (vals, expect) in word_tables.items():
        if len(vals) != expect:
            raise SystemExit(f"{name}: expected {expect} values, got {len(vals)}")
        data = struct.pack("<%dI" % len(vals), *(v & 0xFFFFFFFF for v in vals))
        lines.append(f"{name} = _w('{b64(data)}')")
    lines.append(f"SAP_I0_INDEX = {tuple(sap['i0_index'])!r}")
    (OUT_DIR / "_tables.py").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("tables ok:", ", ".join(list(byte_tables) + list(word_tables)))


def gen_garble(lib: Path):
    src = strip_comments((lib / "playfair" / "hand_garble.c").read_text())
    m = re.search(r"void\s+garble\s*\([^)]*\)\s*\{(.*)\}\s*$", src, re.S)
    if not m:
        raise SystemExit("garble() not found")
    body = m.group(1)
    body = re.sub(r"printf\s*\((?:[^;]*)\)\s*;", "", body)
    stmts = [s.strip() for s in body.split(";")]
    lit = re.compile(r"(?<![\w.])(0[xX][0-9a-fA-F]+|\d+)(?![\w.])")
    assign = re.compile(r"^(\w+(?:\[\d+\])?)\s*([-+*/^|&]?)=(?!=)\s*(.*)$", re.S)
    out = [
        '"""garble() from playfair hand_garble.c, translated by tools/gen_fairplay.py.',
        "",
        "Every value is a CInt that reproduces C integer promotion/overflow rules, and",
        'buffers are uchar arrays, so the arithmetic matches the original exactly."""',
        "from ._cint import L as _L, U as _U, rol8, rol8x, weird_ror8, weird_rol8, weird_rol32",
        "",
        "",
        "def garble(buffer0, buffer1, buffer2, buffer3, buffer4):",
    ]
    variables = set()
    count = 0
    for s in stmts:
        if not s:
            continue
        s = " ".join(s.split())
        if s.startswith("unsigned int"):
            for v in s[len("unsigned int"):].split(","):
                variables.add(v.strip())
            continue
        a = assign.match(s)
        if not a:
            raise SystemExit(f"cannot translate: {s}")
        lhs, op, rhs = a.groups()
        rhs = lit.sub(r"_L(\1)", rhs)
        if "[" in lhs:
            name, idx = lhs.split("[")
            lhs_py = f"{name}[{idx[:-1]}]"
            out.append(f"    {lhs_py} {op}= {rhs}")
        else:
            if lhs not in variables:
                raise SystemExit(f"unknown variable {lhs}")
            if op:
                out.append(f"    {lhs} = _U({lhs} {op} ({rhs}))")
            else:
                out.append(f"    {lhs} = _U({rhs})")
        count += 1
    (OUT_DIR / "_garble.py").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"garble ok: {count} statements, vars={sorted(variables)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    lib = Path(sys.argv[1])
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    gen_tables(lib)
    gen_garble(lib)
    lic = ROOT / "licenses"
    lic.mkdir(exist_ok=True)
    (lic / "playfair-LICENSE.md").write_text((lib / "playfair" / "LICENSE.md").read_text(), encoding="utf-8")
